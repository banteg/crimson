"""The client's GLSL, for both renderers: OpenGL builds it as written, WebGPU runs it translated to WGSL.

Sources are crimson-core/client/shaders/*.{vert,frag} (with common.glsl) and the RTX shaders the Python port shares,
src/crimson/render/rtx/shaders/*.frag. `#include "name"` pulls in a file from either folder or src/grim.

The build writes client_shaders.h: SHADER_<NAME>_<STAGE> and RTX_SHADER_<NAME>_<STAGE> as raw strings without their
#version line (the renderer prepends 330 core or 300 es). The WGSL is committed as wgsl_shaders.h, because its
translation needs tools the build machines lack; the build only checks it is current. Regenerate it with

    uv run python crimson-core/client/shaders.py --wgsl

which needs glslang and spirv-opt (Homebrew's glslang and spirv-tools) and naga (cargo install naga-cli --version
30.0.1): glslang compiles each stage to SPIR-V under relaxed Vulkan rules (loose uniforms become one block, the vertex
stage's in group 1, the fragment stage's in group 0 with its textures after it), spirv-opt splits combined samplers,
and naga writes WGSL. Each stage keeps its uniforms' offsets and its bindings, by name, for the WebGPU renderer.
"""

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
CLIENT_SHADERS = HERE / "shaders"
RTX_SHADERS = ROOT / "src/crimson/render/rtx/shaders"
INCLUDES = (CLIENT_SHADERS, RTX_SHADERS, ROOT / "src/grim")
WGSL_HEADER = HERE / "wgsl_shaders.h"
# The WebGPU renderer's programs: a vertex and a fragment stage each.
PROGRAMS = {
    "classic": (CLIENT_SHADERS / "classic.vert", CLIENT_SHADERS / "classic.frag"),
    "present": (CLIENT_SHADERS / "present.vert", CLIENT_SHADERS / "present.frag"),
    "blit": (CLIENT_SHADERS / "fullscreen.vert", CLIENT_SHADERS / "blit.frag"),
    "tonemap": (CLIENT_SHADERS / "fullscreen.vert", RTX_SHADERS / "hdr_tonemap.frag"),
    "beam": (CLIENT_SHADERS / "beam.vert", RTX_SHADERS / "beam.frag"),
    "creature": (CLIENT_SHADERS / "creature.vert", RTX_SHADERS / "creature.frag"),
    "player": (CLIENT_SHADERS / "creature.vert", RTX_SHADERS / "player.frag"),
}
# glslang's arguments per stage: where each stage's uniform block and textures go.
STAGE_ARGS = {
    "vert": ["--sdub", "VertexUniforms", "1", "0"],
    "frag": ["--sdub", "FragmentUniforms", "0", "0", "--stb", "frag", "1"],
}
# GL type codes of glslang's reflection, by byte size.
TYPE_SIZES = {
    0x1404: 4, 0x1405: 4, 0x1406: 4,  # int, uint, float
    0x8B50: 8, 0x8B51: 12, 0x8B52: 16,  # vec2..4
    0x8B53: 8, 0x8B54: 12, 0x8B55: 16,  # ivec2..4
    0x8B5C: 64,  # mat4
}


def source(path: Path) -> str:
    """A stage with its includes inlined."""

    def include(match: re.Match) -> str:
        for folder in INCLUDES:
            if (folder / match[1]).exists():
                return source(folder / match[1])
        raise SystemExit(f"{path.name}: include {match[1]} not found")

    return re.sub(r'(?m)^#include "([^"]+)"[ \t]*$', include, path.read_text())


def without_version(text: str) -> str:
    return re.sub(r"(?m)^#version[^\n]*\n", "", text, count=1)


def macro(prefix: str, path: Path) -> str:
    return f"{prefix}_{path.stem}_{path.suffix[1:]}".upper()


def stages() -> list[Path]:
    return sorted({stage for program in PROGRAMS.values() for stage in program})


# What the translation does beyond STAGE_ARGS: a change to it changes the WGSL too.
TRANSLATION = "spirv-opt --split-combined-image-sampler --resolve-binding-conflicts; naga --keep-coordinate-space"


def sources_hash() -> str:
    digest = hashlib.sha256(TRANSLATION.encode())
    for path in stages():
        digest.update(f"{path.relative_to(ROOT)}\0{' '.join(STAGE_ARGS[path.suffix[1:]])}\0{source(path)}\0".encode())
    return digest.hexdigest()


def write_shader_headers(out: Path) -> None:
    """client_shaders.h for the build, after checking wgsl_shaders.h still matches its sources."""

    recorded = re.search(r"Source hash: (\w+)", WGSL_HEADER.read_text())
    if not recorded or recorded[1] != sources_hash():
        raise SystemExit(f"{WGSL_HEADER.relative_to(ROOT)} is stale: run `uv run python {Path(__file__).relative_to(ROOT)} --wgsl`")
    lines = ["// Generated by crimson-core/client/shaders.py from client/shaders and the RTX shaders."]
    for prefix, folder in (("SHADER", CLIENT_SHADERS), ("RTX_SHADER", RTX_SHADERS)):
        for path in sorted(p for p in folder.iterdir() if p.suffix in (".frag", ".vert")):
            lines.append(f'#define {macro(prefix, path)} R"GLSL({without_version(source(path))})GLSL"')
    (out / "client_shaders.h").write_text("\n".join(lines) + "\n")


def tool(name: str) -> str:
    path = shutil.which(name)
    if not path:
        raise SystemExit(f"{name} is required to regenerate the WGSL")
    return path


def run(*command: str) -> str:
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode:
        raise SystemExit(f"{' '.join(command)}\n{result.stdout}{result.stderr}")
    return result.stdout


def translate(path: Path, folder: Path) -> dict:
    """One stage's WGSL, uniform block (its size and members' offsets) and bindings."""

    stage = path.suffix[1:]
    glsl = folder / path.name
    glsl.write_text(source(path))
    spirv, split = folder / f"{path.name}.spv", folder / f"{path.name}.split.spv"
    reflection = run(tool("glslang"), "-V", "-R", "--aml", "--amb", *STAGE_ARGS[stage], "-S", stage, "-q",
                     "-o", str(spirv), str(glsl))
    run(tool("spirv-opt"), "--split-combined-image-sampler", "--resolve-binding-conflicts", str(spirv), "-o", str(split))
    wgsl_path = folder / f"{path.name}.wgsl"
    # The GLSL states WebGPU's clip space itself (common.glsl): naga keeps it rather than flip y again.
    run(tool("naga"), "--keep-coordinate-space", str(split), str(wgsl_path))
    wgsl = wgsl_path.read_text()

    uniforms, size = [], 0
    block = reflection.split("Uniform block reflection:")
    for line in block[0].splitlines():
        if match := re.match(r"(\w+): offset (\d+), type ([0-9a-f]+), size (\d+)", line):
            name, offset, kind, count = match[1], int(match[2]), int(match[3], 16), int(match[4])
            if kind not in TYPE_SIZES:
                continue  # a sampler: a binding, not a block member
            if count != 1 and TYPE_SIZES[kind] != 16:
                raise SystemExit(f"{path.name}: uniform array {name} (pack it in vec4s: WGSL uniform arrays need 16-byte strides)")
            uniforms.append((name.removesuffix("[0]"), offset))
            size = max(size, offset + TYPE_SIZES[kind] * count)
    # A texture only ever loaded (texelFetch), never sampled, may hold 32-bit floats, which WebGPU cannot filter:
    # its split-off sampler is declared and never used.
    def sampled(texture: str) -> bool:
        return len(re.findall(rf"\b{texture}_sampler\b", wgsl)) > 1

    bindings = []
    for _group, binding, name, kind in re.findall(r"@group\((\d+)\) @binding\((\d+)\)\s*var(?:<uniform>)? (\w+): ([\w<>]+);", wgsl):
        if kind.startswith("texture"):
            texture = name.removesuffix("_image")
            bindings.append((texture, int(binding), "TEXTURE" if sampled(texture) else "TEXTURE_LOADED"))
        elif kind == "sampler":
            bindings.append((name.removesuffix("_sampler"), int(binding), "SAMPLER"))
        else:
            bindings.append(("uniforms", int(binding), "UNIFORM"))
    group = 1 if stage == "vert" else 0
    return {"wgsl": wgsl, "group": group, "size": (size + 15) // 16 * 16, "uniforms": sorted(uniforms, key=lambda u: u[1]),
            "bindings": sorted(bindings, key=lambda b: b[1])}


def write_wgsl() -> None:
    versions = ", ".join(
        next(line.strip() for line in subprocess.run([tool(name), "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                                       text=True, check=True).stdout.splitlines() if line.strip())
        for name in ("glslang", "spirv-opt", "naga")
    )
    lines = [
        "// Generated by crimson-core/client/shaders.py --wgsl; do not edit.",
        f"// Tools: {versions}",
        f"// Source hash: {sources_hash()}",
        "#pragma once",
        "struct WgslUniform { const char *name; unsigned offset; };",
        "// WGSL_TEXTURE_LOADED: read with textureLoad alone, so it may hold unfilterable floats.",
        "enum WgslKind { WGSL_UNIFORM, WGSL_TEXTURE, WGSL_TEXTURE_LOADED, WGSL_SAMPLER };",
        "struct WgslBinding { const char *name; unsigned binding; WgslKind kind; };",
        "// A stage: its WGSL, the bind group it uses, its uniform block's size and members, and its bindings.",
        "struct WgslStage {",
        "  const char *source;",
        "  unsigned group, uniform_size;",
        "  const WgslUniform *uniforms;",
        "  unsigned uniform_count;",
        "  const WgslBinding *bindings;",
        "  unsigned binding_count;",
        "};",
    ]
    with tempfile.TemporaryDirectory(prefix="crimson-wgsl-") as folder:
        for path in stages():
            stage = translate(path, Path(folder))
            name = macro("WGSL", path)
            uniforms = ", ".join(f'{{"{n}", {o}}}' for n, o in stage["uniforms"]) or '{"", 0}'
            bindings = ", ".join(f'{{"{n}", {b}, WGSL_{k}}}' for n, b, k in stage["bindings"]) or '{"", 0, WGSL_UNIFORM}'
            lines += [
                f"static const WgslUniform {name.lower()}_uniforms[] = {{{uniforms}}};",
                f"static const WgslBinding {name.lower()}_bindings[] = {{{bindings}}};",
                f'static const WgslStage {name} = {{R"WGSL({stage["wgsl"]})WGSL", {stage["group"]}, {stage["size"]},',
                f"    {name.lower()}_uniforms, {len(stage['uniforms'])}, {name.lower()}_bindings, {len(stage['bindings'])}}};",
            ]
    WGSL_HEADER.write_text("\n".join(lines) + "\n")
    print(WGSL_HEADER.relative_to(ROOT))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--wgsl", action="store_true", help="Regenerate wgsl_shaders.h")
    args = parser.parse_args()
    if not args.wgsl:
        parser.error("nothing to do: the build writes client_shaders.h; pass --wgsl to regenerate the WGSL")
    write_wgsl()


if __name__ == "__main__":
    sys.exit(main())
